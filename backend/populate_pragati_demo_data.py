from app.db.supabase import supabase_admin

NOW = datetime.now(timezone.utc)

def days_ago(d):
    return (NOW - timedelta(days=d)).isoformat()

def days_ahead(d):
    return (NOW + timedelta(days=d)).isoformat()

def date_str(d_ago=0, d_ahead=0):
    return (NOW - timedelta(days=d_ago) + timedelta(days=d_ahead)).date().isoformat()

def upsert_table(table_name, records, conflict_col="id"):
    try:
        res = supabase_admin.table(table_name).upsert(records, on_conflict=conflict_col).execute()
        print(f"  [OK] {table_name}: {len(records)} records upserted")
        return res
    except Exception as e:
        print(f"  [ERR] {table_name}: {e}")
        raise e

